#!/usr/bin/env python3
"""Download Google Drive thumbnails for every Drive item in data.js.

Writes  assets/thumbs/drive/<id>.jpg  and  thumbs.js  (window.AZ_THUMBS = {id: "v"|"h"|"s"}).
Thumbnails that are missing, tiny or almost black are skipped so the site
falls back to a branded placeholder instead of showing a black frame.

Usage:  python3 scripts/fetch_thumbs.py        (re-run any time data.js changes)
"""
import concurrent.futures as cf
import io
import json
import pathlib
import re
import urllib.request

from PIL import Image, ImageStat

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "thumbs" / "drive"
OUT.mkdir(parents=True, exist_ok=True)

src = (ROOT / "data.js").read_text(encoding="utf-8")
ids = sorted(set(re.findall(r"\['([A-Za-z0-9_-]{25,})'", src)) | set(re.findall(r"type: 'image', id: '([A-Za-z0-9_-]{25,})'", src)))


def fetch(file_id):
    url = f"https://drive.google.com/thumbnail?id={file_id}&sz=w480"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        data = urllib.request.urlopen(req, timeout=30).read()
        im = Image.open(io.BytesIO(data)).convert("RGB")
    except Exception as exc:  # noqa: BLE001
        return file_id, None, f"error {exc}"
    w, h = im.size
    lum = ImageStat.Stat(im.convert("L"))
    if lum.mean[0] < 14 or lum.stddev[0] < 6:
        return file_id, None, f"blank (mean={lum.mean[0]:.0f}, sd={lum.stddev[0]:.0f})"
    im.save(OUT / f"{file_id}.jpg", "JPEG", quality=78, optimize=True, progressive=True)
    ratio = w / h
    orient = "v" if ratio < 0.9 else ("s" if ratio < 1.15 else "h")
    return file_id, orient, f"{w}x{h}"


results = {}
with cf.ThreadPoolExecutor(max_workers=8) as pool:
    for file_id, orient, info in pool.map(fetch, ids):
        print(f"{file_id}  {orient or '-'}  {info}")
        if orient:
            results[file_id] = orient

(ROOT / "thumbs.js").write_text(
    "/* Auto-generated by scripts/fetch_thumbs.py — do not edit by hand. */\n"
    "window.AZ_THUMBS = " + json.dumps(results, indent=0, sort_keys=True) + ";\n",
    encoding="utf-8",
)
print(f"\n{len(results)}/{len(ids)} thumbnails saved")
